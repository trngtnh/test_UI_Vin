/**
 * Formats a compact, distinct tab label for trim switchers without clipping or duplicate 'Plus' labels.
 */
export function formatShortTrimLabel(versionName: string): string {
  const cleaned = versionName.replace(/^Bản\s+/i, '').trim();
  if (/trần kính/i.test(cleaned)) return 'Plus Trần kính';
  if (/trần thép/i.test(cleaned)) return 'Plus';
  return cleaned.split(' (')[0].trim();
}

export interface VariantDiffResult {
  isSameModel: boolean;
  modelName: string;
  variantA: UnifiedCarVariant;
  variantB: UnifiedCarVariant;
  vLow: UnifiedCarVariant;
  vHigh: UnifiedCarVariant;
  priceDelta: number;
  priceDiffPercent: number;
  priceDiffText: string;
  isSameMotor: boolean;
  motorDiffText: string;
  isSameBattery: boolean;
  batteryDelta: number;
  batteryDiffText: string;
  rangeDelta: number;
  rangeDiffText: string;
  coreFeatureDiff: string;
  diffHighlights: string[];
  priceDiff: number;
  batteryDiff: number;
  rangeDiff: number;
}

/**
 * Phân tích so sánh chi tiết và chênh lệch giữa 2 phiên bản (kể cả cùng một dòng xe hoặc khác dòng)
 */
export function compareTwoVariants(idA: string, idB: string): VariantDiffResult | null {
  const a = VARIANTS_BY_ID[idA];
  const b = VARIANTS_BY_ID[idB];
  if (!a || !b) return null;

  const isSameModel = a.model_id === b.model_id;
  const [vLow, vHigh] = a.price <= b.price ? [a, b] : [b, a];
  const priceDelta = Math.abs(b.price - a.price);
  const priceDiffPercent = vLow.price > 0 ? Math.round((priceDelta / vLow.price) * 1000) / 10 : 0;
  
  // Backward compatibility fields
  const priceDiff = priceDelta;
  const batteryDiff = Math.round((vHigh.battery_kwh - vLow.battery_kwh) * 10) / 10;
  const rangeDiff = vHigh.range_nedc - vLow.range_nedc;

  // Motor formatting
  const isSameMotor = a.motor_power === b.motor_power;
  const motorDiffText = isSameMotor
    ? `Cùng công suất: ${a.motor_power}`
    : `${vLow.motor_power.split('·')[0].trim()} ➔ ${vHigh.motor_power.split('·')[0].trim()}`;

  // Battery formatting
  const batteryDelta = Math.round(Math.abs(vHigh.battery_kwh - vLow.battery_kwh) * 10) / 10;
  const isSameBattery = batteryDelta < 0.1;
  const batteryDiffText = isSameBattery
    ? `Cùng pin: ${vLow.battery_kwh} kWh`
    : `Pin lớn hơn +${batteryDelta} kWh (${vHigh.battery_kwh} vs ${vLow.battery_kwh} kWh)`;

  // Range formatting
  const rangeDelta = Math.abs(vHigh.range_nedc - vLow.range_nedc);
  const rangeDiffText = rangeDelta === 0
    ? `Cùng tầm chạy ${vLow.range_nedc} km`
    : (vHigh.range_nedc >= vLow.range_nedc
        ? `Tầm chạy +${rangeDelta} km (${vHigh.range_nedc} vs ${vLow.range_nedc} km)`
        : `Tầm chạy chênh lệch ${rangeDelta} km (${vHigh.range_nedc} vs ${vLow.range_nedc} km)`);

  // Core feature highlight
  const coreFeatureDiff = `${vHigh.version_name}: ${vHigh.features_highlight || vHigh.adas}`;

  const diffHighlights: string[] = [];
  if (priceDelta > 0) {
    diffHighlights.push(`${vHigh.version_name} cao hơn +${priceDelta.toLocaleString('vi-VN')} đ (+${priceDiffPercent}%)`);
  }
  if (!isSameMotor) {
    diffHighlights.push(`Động cơ: ${motorDiffText}`);
  } else {
    diffHighlights.push(`Động cơ: ${a.motor_power}`);
  }
  if (!isSameBattery) {
    diffHighlights.push(batteryDiffText);
  }
  if (rangeDelta > 0) {
    diffHighlights.push(rangeDiffText);
  }
  if (vHigh.features_highlight) {
    diffHighlights.push(coreFeatureDiff);
  }

  const priceDiffText = priceDelta > 0
    ? `${vHigh.version_name} cao hơn +${priceDelta.toLocaleString('vi-VN')} đ`
    : 'Cùng mức giá niêm yết';

  return {
    isSameModel,
    modelName: a.model_name,
    variantA: a,
    variantB: b,
    vLow,
    vHigh,
    priceDelta,
    priceDiffPercent,
    priceDiffText,
    isSameMotor,
    motorDiffText,
    isSameBattery,
    batteryDelta,
    batteryDiffText,
    rangeDelta,
    rangeDiffText,
    coreFeatureDiff,
    diffHighlights,
    priceDiff,
    batteryDiff,
    rangeDiff,
  };
}

